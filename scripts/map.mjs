#!/usr/bin/env node
// Build the concept map for each eval case, check the viewer in Playwright, and write evals/MAPS.md.
// Full maps (with passage text) and viewer pages go to the gitignored .cache/; the committed map.json keeps
// only a short snippet per passage, since most sources are copyrighted.
// usage: node scripts/map.mjs [case...] [--no-label] [--fresh]
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { chromium } from 'playwright';
import { EVALS, loadDoc, log } from '../skills/paper-playground/scripts/run-eval.mjs';
import { buildMap, mapKey } from '../lib/map.mjs';
import { renderMapHtml } from '../lib/map-view.mjs';

const args = process.argv.slice(2), flag = f => args.includes(f), only = args.filter(a => !a.startsWith('--'));
const cases = readdirSync(EVALS).filter(d => existsSync(join(EVALS, d, 'case.json')) && (!only.length || only.includes(d)));

/** Load the viewer, drive it, and screenshot it. Returns the failures (empty = pass). */
async function check(browser, file, map, dir) {
  const fails = [], ctx = await browser.newContext({ viewport: { width: 1120, height: 820 }, deviceScaleFactor: 2, colorScheme: 'light', reducedMotion: 'reduce' });
  const page = await ctx.newPage();
  page.on('console', m => { if (m.type() === 'error') fails.push(`console: ${m.text()}`); });
  page.on('pageerror', e => fails.push(`pageerror: ${e.message}`));
  await page.goto(`file://${file}`);
  const pts = await page.evaluate(() => window.__map.screen().map(p => [p.x, p.y]));
  const box = await page.locator('.stage canvas').boundingBox();
  if (pts.length !== map.n) fails.push(`${pts.length} points drawn, expected ${map.n}`);
  if (pts.some(([x, y]) => !(x >= 0 && y >= 0 && x <= box.width && y <= box.height))) fails.push('a point is off the canvas');
  if (await page.locator('.legend li').count() !== map.k) fails.push('legend count != k');
  const p = pts[0];
  await page.mouse.move(box.x + p[0], box.y + p[1]);
  if (!(await page.locator('.tip').isVisible())) fails.push('hover shows no passage');
  await page.mouse.move(0, 0);
  const sec = map.chunks[0].section;
  const lit = await page.evaluate(s => { postMessage({ type: 'pp:param-hover', section: s }, '*'); return new Promise(r => setTimeout(() => r(!!window.__map.st.sections?.(s)), 50)); }, sec);
  if (!lit) fails.push('pp:param-hover does not highlight its section');
  await page.evaluate(() => postMessage({ type: 'pp:param-hover', section: null }, '*'));
  await page.locator('.plate').screenshot({ path: join(dir, 'map-light.png') });
  await page.click('button[data-mode="3d"]');
  const before = await page.evaluate(() => window.__map.screen()[0].x);
  await page.mouse.move(box.x + box.width / 2, box.y + 30); await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + 120, box.y + 60, { steps: 6 }); await page.mouse.up(); await page.mouse.move(0, 0);
  if (await page.evaluate(() => window.__map.screen()[0].x) === before) fails.push('dragging in 3D does not rotate');
  await page.emulateMedia({ colorScheme: 'dark' }); await page.waitForTimeout(150);
  await page.locator('.plate').screenshot({ path: join(dir, 'map-dark.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) fails.push('horizontal scroll at phone width');
  await ctx.close();
  return fails;
}

const browser = await chromium.launch(), rows = [];
for (const name of cases) {
  const dir = join(EVALS, name), doc = await loadDoc(dir, JSON.parse(readFileSync(join(dir, 'case.json'), 'utf8')));
  const cached = join(dir, '.cache', 'map.json'), key = mapKey(doc.sections.map(s => s.text).join('\n\n'));
  let map = existsSync(cached) && !flag('--fresh') ? JSON.parse(readFileSync(cached, 'utf8')) : null;
  if (map?.key !== key || (!flag('--no-label') && map.label_model === 'section')) map = await buildMap(doc, { label: !flag('--no-label') });
  writeFileSync(cached, JSON.stringify(map, null, 2));
  if (map.error) { log(name, map.error); rows.push({ name, map, fails: [map.error] }); continue; }
  const html = join(dir, '.cache', 'map.html');
  writeFileSync(html, renderMapHtml(map));
  const fails = await check(browser, html, map, dir);
  const slim = { ...map, chunks: map.chunks.map(({ text, ...c }) => ({ ...c, snippet: text.length > 100 ? `${text.slice(0, 100)}…` : text })) };
  writeFileSync(join(dir, 'map.json'), JSON.stringify(slim, null, 2) + '\n');
  log(name, `${map.n} chunks · ${map.method} · k=${map.k} · ${fails.length ? `FAIL ${fails.join('; ')}` : 'viewer ok'}`);
  rows.push({ name, map, fails });
}
await browser.close();

if (!only.length) {
  const s = ms => ms == null ? '–' : (ms / 1e3).toFixed(1);
  writeFileSync(join(EVALS, 'MAPS.md'), `# Concept maps

Generated by \`node scripts/map.mjs\`. Embeddings: ${rows[0]?.map.embed_model} (local). Layout: t-SNE (seeded; 2D and 3D are separate runs), PCA below 30 chunks. Clusters: cosine k-means, k by silhouette. Labels: Haiku from the 4 passages nearest each centroid.

| case | chunks | layout | k | silhouette | cluster labels (size) | embed s | label s | viewer |
|---|---|---|---|---|---|---|---|---|
${rows.map(({ name, map: m, fails }) => m.error ? `| ${name} | ${m.n} | – | – | – | – | – | – | ${m.error} |` :
    `| ${name} | ${m.n} | ${m.method}${m.perplexity ? ` (perp ${m.perplexity})` : ''} | ${m.k} | ${m.silhouette ?? '–'} | ${m.clusters.map(c => `${c.label} (${c.size})`).join('; ')}${m.label_model === 'section' ? ' *(section titles)*' : ''} | ${s(m.ms.embed)} | ${s(m.ms.label)} | ${fails.length ? `FAIL: ${fails.join('; ')}` : 'pass'} |`).join('\n')}

Screenshots: \`evals/<case>/map-light.png\` (2D) and \`map-dark.png\` (3D).
`);
}
process.exit(rows.some(r => r.fails.length) ? 1 : 0);
