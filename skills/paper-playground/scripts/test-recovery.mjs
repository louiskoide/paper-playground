#!/usr/bin/env node
// Exercise the repair and fallback steps on real failures, since every eval's first attempt passes.
// Each entry in evals/breaks.json plants one bug in a case's passing playground.js: the self-test
// must catch it, and one repair call must fix it. Cases whose extraction has a fallback also run the
// fallback step on its own. Writes evals/RECOVERY.md.
// usage: node test-recovery.mjs [case...] [--no-repair] [--no-fallback] [--concurrency N]
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { chromium } from 'playwright';
import { EVALS, log, loadDoc, check, attempt } from './run-eval.mjs';

const args = process.argv.slice(2), flag = f => args.includes(f);
const ci = args.indexOf('--concurrency'), concurrency = ci >= 0 ? +args[ci + 1] : 3;
const only = args.filter((a, i) => !a.startsWith('--') && args[i - 1] !== '--concurrency');
const breaks = JSON.parse(readFileSync(join(EVALS, 'breaks.json'), 'utf8'));
const load = name => {
  const dir = join(EVALS, name);
  return { dir, spec: JSON.parse(readFileSync(join(dir, 'case.json'), 'utf8')), x: JSON.parse(readFileSync(join(dir, 'extraction.json'), 'utf8')) };
};
const cost = calls => +calls.reduce((s, c) => s + (c.cost || 0), 0).toFixed(3);

async function runBreak(name, b, browser) {
  const { dir, spec, x } = load(name), code = readFileSync(join(dir, 'playground.js'), 'utf8').trim(), id = `${name}/${b.name}`;
  if (!code.includes(b.find)) throw new Error(`${id}: "find" text is not in playground.js`);
  const work = join(dir, '.cache', 'breaks', b.name); mkdirSync(work, { recursive: true });
  const broken = code.replace(b.find, () => b.replace);
  const seeded = await check(broken, x, join(work, 'broken'), browser), calls = [];
  log(id, seeded.ok ? 'NOT caught: the broken playground passes its self-test' : `caught: ${seeded.failures.length} failure(s)`);
  const row = { case: name, break: b.name, kind: b.kind, caught: !seeded.ok, seeded: seeded.failures, calls };
  if (seeded.ok || flag('--no-repair')) return row;
  const r = await attempt(id, work, 'repair', x, await loadDoc(dir, spec), browser, calls, { code: broken, failures: seeded.failures });
  return Object.assign(row, { repaired: r.ok, failures: r.failures, restored: !!r.code?.includes(b.find), observed: r.observed, cost_usd: cost(calls) });
}

async function runFallback(name, browser) {
  const { dir, spec, x } = load(name), work = join(dir, '.cache', 'fallback-only'), calls = [];
  mkdirSync(work, { recursive: true });
  const r = await attempt(`${name}/fallback`, work, 'fallback', x.fallback, await loadDoc(dir, spec), browser, calls);
  return { case: name, archetype: x.fallback.archetype, ok: r.ok, refused: r.refused, failures: r.failures, observed: r.observed, cost_usd: cost(calls) };
}

const cases = Object.keys(breaks).filter(c => !only.length || only.includes(c));
const jobs = [
  ...cases.flatMap(c => breaks[c].map(b => ['break', () => runBreak(c, b, browser)])),
  ...(flag('--no-fallback') ? [] : cases.filter(c => load(c).x.fallback).map(c => ['fallback', () => runFallback(c, browser)])),
];
const browser = await chromium.launch(), results = { break: [], fallback: [] }, queue = [...jobs];
await Promise.all(Array.from({ length: Math.min(concurrency, queue.length) }, async () => {
  while (queue.length) { const [kind, run] = queue.shift(); results[kind].push(await run()); }
}));
await browser.close();

const cell = s => String(s ?? '').replace(/\|/g, '/').replace(/\n/g, ' ');
const short = fs => cell((fs || []).slice(0, 2).map(f => f.length > 110 ? `${f.slice(0, 110)}…` : f).join('; ') + (fs?.length > 2 ? ` (+${fs.length - 2})` : ''));
const lines = ['# Recovery tests', '', 'Generated by `scripts/test-recovery.mjs`. Each row plants one bug from `breaks.json` in a passing playground, then gives the self-test failures to one repair call. "Restored" means the repair contains the original line verbatim.', '',
  '| case | planted bug | caught by | repair | restored | still failing | cost |', '|---|---|---|---|---|---|---|',
  ...results.break.sort((a, b) => `${a.case}${a.break}`.localeCompare(`${b.case}${b.break}`)).map(r =>
    `| ${r.case} | ${cell(r.kind)} | ${r.caught ? short(r.seeded) : '**not caught**'} | ${!r.caught ? '–' : r.repaired == null ? 'skipped' : r.repaired ? 'pass' : '**fail**'} | ${r.restored == null ? '–' : r.restored ? 'yes' : 'no'} | ${short(r.repaired === false ? r.failures : [])} | ${r.cost_usd != null ? `$${r.cost_usd}` : '–'} |`)];
if (results.fallback.length) lines.push('', '## Fallback on its own', '', '| case | archetype | outcome | failures | cost |', '|---|---|---|---|---|',
  ...results.fallback.map(r => `| ${r.case} | ${r.archetype} | ${r.ok ? 'pass' : r.refused ? 'refused' : '**fail**'} | ${short(r.ok ? [] : r.failures)} | $${r.cost_usd} |`));
writeFileSync(join(EVALS, 'RECOVERY.md'), lines.join('\n') + '\n');
writeFileSync(join(EVALS, 'recovery.json'), JSON.stringify(results, null, 2));
